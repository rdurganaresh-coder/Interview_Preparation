package com.leetcode.dynamic_programming;

class Solution0188 {
    private Integer[][][] f;
    private int[] prices;
    private int n;

    public int maxProfit(int k, int[] prices) {
        n = prices.length;
        this.prices = prices;
        f = new Integer[n][k + 1][2];
        return dfs(0, k, 0);
    }

    private int dfs(int i, int j, int k) {
        if (i >= n) {
            return 0;
        }
        if (f[i][j][k] != null) {
            return f[i][j][k];
        }
        int ans = dfs(i + 1, j, k);
        if (k > 0) {
            ans = Math.max(ans, prices[i] + dfs(i + 1, j, 0));
        } else if (j > 0) {
            ans = Math.max(ans, -prices[i] + dfs(i + 1, j - 1, 1));
        }
        return f[i][j][k] = ans;
    }

    // ===== Generated test cases (from the problem examples) =====
    private static String _tcShow(Object o) {
        String s = java.util.Arrays.deepToString(new Object[] {o});
        return s.substring(1, s.length() - 1);
    }

    public static void main(String[] args) {
        Solution0188 _tcSol = new Solution0188();
        System.out.println("Test 1");
        System.out.println("  Input   : " + "k = 2, prices = [2,4,1]");
        try {
            int k = 2;
            int[] prices = new int[]{2, 4, 1};
            System.out.println("  Output  : " + _tcShow(_tcSol.maxProfit(k, prices)));
        } catch (Throwable e) {
            System.out.println("  Output  : ERROR " + e);
        }
        System.out.println("  Expected: " + "2");
        System.out.println();

        System.out.println("Test 2");
        System.out.println("  Input   : " + "k = 2, prices = [3,2,6,5,0,3]");
        try {
            int k = 2;
            int[] prices = new int[]{3, 2, 6, 5, 0, 3};
            System.out.println("  Output  : " + _tcShow(_tcSol.maxProfit(k, prices)));
        } catch (Throwable e) {
            System.out.println("  Output  : ERROR " + e);
        }
        System.out.println("  Expected: " + "7");
        System.out.println();
    }
}