package com.leetcode.strings;

class Solution0291 {
    private Set<String> vis;
    private Map<Character, String> d;
    private String p;
    private String s;
    private int m;
    private int n;

    public boolean wordPatternMatch(String pattern, String s) {
        vis = new HashSet<>();
        d = new HashMap<>();
        this.p = pattern;
        this.s = s;
        m = p.length();
        n = s.length();
        return dfs(0, 0);
    }

    private boolean dfs(int i, int j) {
        if (i == m && j == n) {
            return true;
        }
        if (i == m || j == n || m - i > n - j) {
            return false;
        }
        char c = p.charAt(i);
        for (int k = j + 1; k <= n; ++k) {
            String t = s.substring(j, k);
            if (d.getOrDefault(c, "").equals(t)) {
                if (dfs(i + 1, k)) {
                    return true;
                }
            }
            if (!d.containsKey(c) && !vis.contains(t)) {
                d.put(c, t);
                vis.add(t);
                if (dfs(i + 1, k)) {
                    return true;
                }
                vis.remove(t);
                d.remove(c);
            }
        }
        return false;
    }

    // ===== Generated test cases (from the problem examples) =====
    private static String _tcShow(Object o) {
        String s = java.util.Arrays.deepToString(new Object[] {o});
        return s.substring(1, s.length() - 1);
    }

    public static void main(String[] args) {
        Solution0291 _tcSol = new Solution0291();
        System.out.println("Test 1");
        System.out.println("  Input   : " + "pattern = \"abab\", s = \"redblueredblue\"");
        try {
            String pattern = "abab";
            String s = "redblueredblue";
            System.out.println("  Output  : " + _tcShow(_tcSol.wordPatternMatch(pattern, s)));
        } catch (Throwable e) {
            System.out.println("  Output  : ERROR " + e);
        }
        System.out.println("  Expected: " + "true");
        System.out.println();

        System.out.println("Test 2");
        System.out.println("  Input   : " + "pattern = \"aaaa\", s = \"asdasdasdasd\"");
        try {
            String pattern = "aaaa";
            String s = "asdasdasdasd";
            System.out.println("  Output  : " + _tcShow(_tcSol.wordPatternMatch(pattern, s)));
        } catch (Throwable e) {
            System.out.println("  Output  : ERROR " + e);
        }
        System.out.println("  Expected: " + "true");
        System.out.println();

        System.out.println("Test 3");
        System.out.println("  Input   : " + "pattern = \"aabb\", s = \"xyzabcxzyabc\"");
        try {
            String pattern = "aabb";
            String s = "xyzabcxzyabc";
            System.out.println("  Output  : " + _tcShow(_tcSol.wordPatternMatch(pattern, s)));
        } catch (Throwable e) {
            System.out.println("  Output  : ERROR " + e);
        }
        System.out.println("  Expected: " + "false");
        System.out.println();
    }
}