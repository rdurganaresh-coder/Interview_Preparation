package com.leetcode.strings;

class Solution0809 {
    public int expressiveWords(String s, String[] words) {
        int ans = 0;
        for (String t : words) {
            if (check(s, t)) {
                ++ans;
            }
        }
        return ans;
    }

    private boolean check(String s, String t) {
        int m = s.length(), n = t.length();
        if (n > m) {
            return false;
        }
        int i = 0, j = 0;
        while (i < m && j < n) {
            if (s.charAt(i) != t.charAt(j)) {
                return false;
            }
            int k = i;
            while (k < m && s.charAt(k) == s.charAt(i)) {
                ++k;
            }
            int c1 = k - i;
            i = k;
            k = j;
            while (k < n && t.charAt(k) == t.charAt(j)) {
                ++k;
            }
            int c2 = k - j;
            j = k;
            if (c1 < c2 || (c1 < 3 && c1 != c2)) {
                return false;
            }
        }
        return i == m && j == n;
    }

    // ===== Generated test cases (from the problem examples) =====
    private static String _tcShow(Object o) {
        String s = java.util.Arrays.deepToString(new Object[] {o});
        return s.substring(1, s.length() - 1);
    }

    public static void main(String[] args) {
        Solution0809 _tcSol = new Solution0809();
        System.out.println("Test 1");
        System.out.println("  Input   : " + "s = \"heeellooo\", words = [\"hello\", \"hi\", \"helo\"]");
        try {
            String s = "heeellooo";
            String[] words = new String[]{"hello", "hi", "helo"};
            System.out.println("  Output  : " + _tcShow(_tcSol.expressiveWords(s, words)));
        } catch (Throwable e) {
            System.out.println("  Output  : ERROR " + e);
        }
        System.out.println("  Expected: " + "1");
        System.out.println();

        System.out.println("Test 2");
        System.out.println("  Input   : " + "s = \"zzzzzyyyyy\", words = [\"zzyy\",\"zy\",\"zyy\"]");
        try {
            String s = "zzzzzyyyyy";
            String[] words = new String[]{"zzyy", "zy", "zyy"};
            System.out.println("  Output  : " + _tcShow(_tcSol.expressiveWords(s, words)));
        } catch (Throwable e) {
            System.out.println("  Output  : ERROR " + e);
        }
        System.out.println("  Expected: " + "3");
        System.out.println();
    }
}